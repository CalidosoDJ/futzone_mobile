class Cancha {
  final int id;
  final String nombre;
  final String zona;
  final String direccion;
  final String telefono;
  final int precio;
  final String imagen;
  final double calificacion;

  const Cancha({
    required this.id,
    required this.nombre,
    required this.zona,
    required this.direccion,
    required this.telefono,
    required this.precio,
    required this.imagen,
    required this.calificacion,
  });
}